using System;
using System.Collections.Generic;
using Idol.Unity;
using UnityEngine;

namespace RelicDrift
{
    /// <summary>
    /// A complete one-scene arcade game. All world visuals are the three unmodified Idol splats.
    /// Collision, lane logic, and animation operate on rigid transforms; there are no generated meshes.
    /// </summary>
    public sealed class RelicDriftGame : MonoBehaviour
    {
        [Header("Generated by Idol Studio; no mesh substitutes")]
        public IdolGaussianAsset CourierAsset;
        public IdolGaussianAsset CrystalAsset;
        public IdolGaussianAsset RockAsset;
        public Shader GaussianShader;
        [Header("Rigid display orientation only")]
        public Vector3 CourierRotation = new Vector3(0, -90f, 0);
        public Vector3 CrystalRotation;
        public Vector3 RockRotation;

        const float LaneWidth = 2.6f;
        const float SpawnZ = 38f;
        const string BestKey = "RelicDrift.HighScore.v1";
        readonly GameRules rules = new GameRules();
        readonly List<FlightObject> flight = new List<FlightObject>();
        readonly Stack<Transform> crystalPool = new Stack<Transform>();
        readonly Stack<Transform> rockPool = new Stack<Transform>();
        System.Random random;
        RelicHud hud;
        RelicAudio audioBus;
        Transform world, courier, titleCrystal, titleRock;
        IdolGaussianRenderer courierRenderer;
        Camera gameCamera;
        Vector3 cameraHome;
        int lane = 1, highScore, row;
        float spawnWait, invulnerable, shake;
        bool ready, endHandled;
        float gameClock;

        sealed class FlightObject
        {
            public Transform Transform;
            public int Lane;
            public bool Crystal;
            public bool Resolved;
        }

        public RunPhase State => rules.Phase;
        public int Score => rules.Score;
        public int Lives => rules.Lives;
        public int HighScore => highScore;
        public int Crystals => rules.Crystals;
        public float SecondsRemaining => rules.SecondsRemaining;
        public bool IsReady => ready;

        void Start()
        {
            Application.targetFrameRate = 60;
            QualitySettings.vSyncCount = 1;
            highScore = PlayerPrefs.GetInt(BestKey, 0);
            random = new System.Random(20261031);
            BuildCamera();
            world = new GameObject("Idol-generated world").transform;
            world.SetParent(transform, false);
            audioBus = gameObject.AddComponent<RelicAudio>();
            audioBus.Initialize();
            hud = gameObject.AddComponent<RelicHud>();
            hud.Build(this, gameCamera);
            var missing = new List<string>();
            if (!CourierAsset || CourierAsset.Count == 0) missing.Add("Courier");
            if (!CrystalAsset || CrystalAsset.Count == 0) missing.Add("Sun crystal");
            if (!RockAsset || RockAsset.Count == 0) missing.Add("Void rock");
            if (!GaussianShader) missing.Add("Idol Gaussian shader");
            if (missing.Count > 0)
            {
                string message = "Missing: " + string.Join(", ", missing) + ".";
                Debug.LogError(message);
                hud.ShowError(message);
                hud.Refresh(rules, highScore, audioBus.Muted, lane);
                return;
            }
            courier = CreateVisual("Courier · Idol splat", CourierAsset, 2.55f, CourierRotation);
            courierRenderer = courier.GetComponentInChildren<IdolGaussianRenderer>();
            titleCrystal = CreateVisual("Sun crystal · Idol splat", CrystalAsset, 2.5f, CrystalRotation);
            titleRock = CreateVisual("Void rock · Idol splat", RockAsset, 3.4f, RockRotation);
            ready = true;
            ReturnToTitle();
        }

        void BuildCamera()
        {
            gameCamera = Camera.main;
            if (!gameCamera) gameCamera = new GameObject("Main Camera", typeof(Camera)).GetComponent<Camera>();
            gameCamera.gameObject.tag = "MainCamera";
            gameCamera.transform.SetParent(transform, false);
            cameraHome = new Vector3(0, 6f, -11f);
            gameCamera.transform.position = cameraHome;
            gameCamera.transform.rotation = Quaternion.LookRotation(new Vector3(0, 0, 9f) - cameraHome);
            gameCamera.clearFlags = CameraClearFlags.SolidColor;
            gameCamera.backgroundColor = new Color(.02f, .035f, .065f);
            gameCamera.fieldOfView = 52f;
            gameCamera.nearClipPlane = .1f;
            gameCamera.farClipPlane = 100f;
            gameCamera.allowHDR = false;
            if (!gameCamera.GetComponent<AudioListener>()) gameCamera.gameObject.AddComponent<AudioListener>();
        }

        void Update()
        {
            float dt = Mathf.Min(Time.deltaTime, .1f);
            if (Input.GetKeyDown(KeyCode.M)) ToggleSound();
            if (Input.GetKeyDown(KeyCode.F11))
                Screen.fullScreenMode = Screen.fullScreen ? FullScreenMode.Windowed : FullScreenMode.FullScreenWindow;
            if (ready)
            {
                HandleInput();
                if (rules.Phase == RunPhase.Playing)
                {
                    gameClock += dt;
                    invulnerable = Mathf.Max(0, invulnerable - dt);
                    MoveCourier(dt);
                    MoveField(dt);
                    rules.Advance(dt);
                    if (rules.Phase == RunPhase.Completed || rules.Phase == RunPhase.GameOver) EndRun();
                }
                else if (rules.Phase == RunPhase.Title) AttractMode();
                // Every crystal uses exactly the same rotation so the splat renderer can share its depth ordering.
                float spinClock = rules.Phase == RunPhase.Title ? Time.time : gameClock;
                Quaternion crystalSpin = Quaternion.Euler(0, spinClock * 16f, 0);
                titleCrystal.rotation = crystalSpin;
                for (int i = 0; i < flight.Count; i++)
                    if (flight[i].Crystal) flight[i].Transform.rotation = crystalSpin;
                if (courierRenderer)
                    courierRenderer.opacity = invulnerable > 0 && rules.Phase == RunPhase.Playing
                        ? .55f + .45f * Mathf.Sin(Time.time * 28f) * Mathf.Sin(Time.time * 28f) : 1f;
            }
            shake = Mathf.Max(0, shake - dt * 2.4f);
            gameCamera.transform.position = cameraHome + new Vector3(Mathf.Sin(Time.unscaledTime * 73f), Mathf.Cos(Time.unscaledTime * 61f), 0) * shake * .09f;
            hud.Animate(Time.unscaledDeltaTime);
            hud.Refresh(rules, highScore, audioBus.Muted, lane);
        }

        void HandleInput()
        {
            if (Input.GetKeyDown(KeyCode.Space) || Input.GetKeyDown(KeyCode.Return) || Input.GetKeyDown(KeyCode.KeypadEnter))
                PrimaryAction();
            if (Input.GetKeyDown(KeyCode.P) || Input.GetKeyDown(KeyCode.Escape)) TogglePause();
            if (rules.Phase != RunPhase.Playing) return;
            if (Input.GetKeyDown(KeyCode.LeftArrow) || Input.GetKeyDown(KeyCode.A)) SelectLane(lane - 1);
            if (Input.GetKeyDown(KeyCode.RightArrow) || Input.GetKeyDown(KeyCode.D)) SelectLane(lane + 1);
        }

        public void PrimaryAction()
        {
            if (rules.Phase == RunPhase.Paused) TogglePause();
            else if (rules.Phase != RunPhase.Playing) StartRun();
        }

        public void StartRun()
        {
            if (!ready) return;
            ClearField();
            rules.Start();
            lane = 1;
            row = 0;
            gameClock = 0;
            spawnWait = .25f;
            invulnerable = 0;
            endHandled = false;
            shake = 0;
            // A reproducible fair route, with enough space to switch at least one lane between rows.
            random = new System.Random(20261031);
            courier.position = Vector3.zero;
            courier.rotation = Quaternion.identity;
            courier.localScale = Vector3.one;
            titleCrystal.gameObject.SetActive(false);
            titleRock.gameObject.SetActive(false);
            audioBus.SetPaused(false);
            audioBus.Launch();
            hud.Announce("CATCH GOLD. DODGE ROCKS.");
            hud.Refresh(rules, highScore, audioBus.Muted, lane);
        }

        public void ReturnToTitle()
        {
            if (!ready) return;
            ClearField();
            rules.ShowTitle();
            invulnerable = 0;
            titleCrystal.gameObject.SetActive(true);
            titleRock.gameObject.SetActive(true);
            audioBus.SetPaused(false);
            AttractMode();
            hud.Refresh(rules, highScore, audioBus.Muted, lane);
        }

        public void TogglePause()
        {
            if (!ready) return;
            rules.TogglePause();
            audioBus.SetPaused(rules.Phase == RunPhase.Paused);
            hud.Refresh(rules, highScore, audioBus.Muted, lane);
        }

        public void ToggleSound() { if (audioBus) audioBus.ToggleMute(); }
        public void PlayUiClick() { if (audioBus) audioBus.Click(); }
        public void SelectLane(int selected)
        {
            if (rules.Phase == RunPhase.Playing) lane = Mathf.Clamp(selected, 0, 2);
        }

        void MoveCourier(float dt)
        {
            float x = Mathf.Lerp(courier.position.x, LaneX(lane), 1f - Mathf.Exp(-dt * 16f));
            float bank = Mathf.Clamp((LaneX(lane) - courier.position.x) * -11f, -24f, 24f);
            courier.position = new Vector3(x, Mathf.Sin(gameClock * 3.1f) * .07f, 0);
            courier.rotation = Quaternion.Slerp(courier.rotation, Quaternion.Euler(0, 0, bank), 1f - Mathf.Exp(-dt * 10f));
        }

        void MoveField(float dt)
        {
            float speed = Mathf.Lerp(13f, 22f, rules.Progress);
            spawnWait -= dt;
            if (spawnWait <= 0 && rules.SecondsRemaining > 2.3f)
            {
                SpawnRow();
                spawnWait += Mathf.Lerp(1.42f, 1.05f, rules.Progress);
            }
            for (int i = flight.Count - 1; i >= 0; i--)
            {
                var actor = flight[i];
                Vector3 p = actor.Transform.position;
                float previous = p.z;
                p.z -= speed * dt;
                actor.Transform.position = p;
                if (!actor.Resolved && previous > .25f && p.z <= .25f)
                {
                    actor.Resolved = true;
                    if (Mathf.Abs(p.x - courier.position.x) < 1.1f)
                    {
                        if (actor.Crystal)
                        {
                            Collect();
                            RecycleAt(i);
                            continue;
                        }
                        if (invulnerable <= 0) Hit();
                        RecycleAt(i);
                        continue;
                    }
                }
                if (p.z < -7f) RecycleAt(i);
            }
        }

        void SpawnRow()
        {
            row++;
            int safeLane = random.Next(3);
            int rockLane = (safeLane + 1 + random.Next(2)) % 3;
            Spawn(false, rockLane, SpawnZ);
            // The first few rows teach the pattern. Later rows still always leave a safe lane.
            if (row > 6 && random.NextDouble() < .32)
                Spawn(false, 3 - safeLane - rockLane, SpawnZ);
            Spawn(true, safeLane, SpawnZ);
            if (row % 4 == 0) Spawn(true, safeLane, SpawnZ + 3.4f);
        }

        void Spawn(bool crystal, int chosenLane, float z)
        {
            var pool = crystal ? crystalPool : rockPool;
            Transform visual = pool.Count > 0 ? pool.Pop() : CreateVisual(
                crystal ? "Sun crystal · Idol splat" : "Void rock · Idol splat",
                crystal ? CrystalAsset : RockAsset, crystal ? 1.35f : 2.25f,
                crystal ? CrystalRotation : RockRotation);
            visual.gameObject.SetActive(true);
            visual.position = new Vector3(LaneX(chosenLane), crystal ? .1f : 0f, z);
            visual.rotation = crystal ? Quaternion.Euler(0, Time.time * 16f, 0) : Quaternion.identity;
            flight.Add(new FlightObject { Transform = visual, Lane = chosenLane, Crystal = crystal });
        }

        void Collect()
        {
            int before = rules.Multiplier;
            int points = rules.Collect();
            if (points == 0) return;
            audioBus.Pickup();
            hud.Announce(rules.Multiplier > before ? "+" + points + "  ·  MULTIPLIER x" + rules.Multiplier : "+" + points + "  SUN CRYSTAL");
        }

        void Hit()
        {
            if (!rules.Hit()) return;
            invulnerable = 1.1f;
            shake = 1f;
            audioBus.Hit();
            hud.Announce(rules.Lives > 0 ? "HULL HIT  ·  STREAK LOST" : "SIGNAL LOST", true);
            if (rules.Phase == RunPhase.GameOver) EndRun();
        }

        void EndRun()
        {
            if (endHandled) return;
            endHandled = true;
            if (rules.Score > highScore)
            {
                highScore = rules.Score;
                PlayerPrefs.SetInt(BestKey, highScore);
                PlayerPrefs.Save();
            }
            if (rules.Phase == RunPhase.Completed) audioBus.Finish();
            audioBus.SetPaused(true);
        }

        void AttractMode()
        {
            courier.position = new Vector3(6.5f, .8f + Mathf.Sin(Time.time * 1.4f) * .17f, 6f);
            courier.localScale = Vector3.one * 3.4f;
            // Counter the gameplay heading to present the generated courier in a three-quarter title pose.
            courier.rotation = Quaternion.Euler(0, Mathf.Sin(Time.time * .3f) * 12f + 72f, Mathf.Sin(Time.time * .75f) * 4f);
            titleCrystal.position = new Vector3(1.8f, 2.0f + Mathf.Sin(Time.time * 1.1f) * .12f, 12f);
            titleRock.position = new Vector3(18f, 1.8f, 17f);
            titleRock.rotation = Quaternion.identity;
        }

        Transform CreateVisual(string title, IdolGaussianAsset asset, float size, Vector3 euler)
        {
            var root = new GameObject(title).transform;
            root.SetParent(world, false);
            var shape = new GameObject("Unmodified Idol Gaussian data", typeof(IdolGaussianRenderer)).transform;
            shape.SetParent(root, false);
            float longest = Mathf.Max(asset.bounds.size.x, Mathf.Max(asset.bounds.size.y, asset.bounds.size.z));
            float scale = size / Mathf.Max(.01f, longest);
            shape.localRotation = Quaternion.Euler(euler);
            shape.localScale = Vector3.one * scale;
            shape.localPosition = -(shape.localRotation * (asset.bounds.center * scale));
            var renderer = shape.GetComponent<IdolGaussianRenderer>();
            renderer.asset = asset;
            renderer.shader = GaussianShader;
            renderer.opacity = 1f;
            return root;
        }

        void RecycleAt(int index)
        {
            var actor = flight[index];
            actor.Transform.gameObject.SetActive(false);
            (actor.Crystal ? crystalPool : rockPool).Push(actor.Transform);
            flight.RemoveAt(index);
        }

        void ClearField() { for (int i = flight.Count - 1; i >= 0; i--) RecycleAt(i); }
        static float LaneX(int index) { return (index - 1) * LaneWidth; }

        void OnApplicationFocus(bool focus)
        {
            if (!focus && ready && rules.Phase == RunPhase.Playing) TogglePause();
        }

#if UNITY_EDITOR || DEVELOPMENT_BUILD
        // These are deterministic validation hooks. They do not alter the release game's input or rules.
        public void DebugStartRun() { StartRun(); }
        public void DebugCollect() { Collect(); hud.Refresh(rules, highScore, audioBus.Muted, lane); }
        public void DebugHit() { Hit(); hud.Refresh(rules, highScore, audioBus.Muted, lane); }
        public void DebugAdvanceTime(float seconds)
        {
            rules.Advance(seconds);
            if (rules.Phase == RunPhase.Completed || rules.Phase == RunPhase.GameOver) EndRun();
            hud.Refresh(rules, highScore, audioBus.Muted, lane);
        }
        public void DebugTogglePause() { TogglePause(); }
#endif
    }
}
